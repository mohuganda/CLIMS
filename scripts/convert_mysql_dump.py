#!/usr/bin/env python3
"""Convert this repository's MySQL dump; reject unsupported syntax rather than lose data."""

import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "infra/compose/clims_dump_11Nov2026.sql"
MIGRATIONS = ROOT / "backend/internal/database/migrations"


def values(sql):
    """Translate MySQL backslash escapes inside string literals only."""
    result = []
    i = 0
    quoted = False
    rows = 0
    escapes = {"0": "\0", "b": "\b", "n": "\n", "r": "\r", "t": "\t", "Z": "\x1a"}
    while i < len(sql):
        c = sql[i]
        if c == "'":
            if quoted and i + 1 < len(sql) and sql[i + 1] == "'":
                result.append("''")
                i += 2
                continue
            quoted = not quoted
            result.append(c)
        elif quoted and c == "\\":
            i += 1
            if i >= len(sql):
                raise ValueError("Incomplete escape")
            c = escapes.get(sql[i], sql[i])
            if c == "\0":
                raise ValueError("PostgreSQL text cannot contain NUL")
            result.append("''" if c == "'" else c)
        else:
            if not quoted and c == "(":
                rows += 1
            result.append(c)
        i += 1
    if quoted:
        raise ValueError("Unterminated string")
    return "".join(result), rows


def convert():
    source = SOURCE.read_text()
    schema, indexes, seed, sequences = [], [], [], []
    counts = {}
    for match in re.finditer(r"CREATE TABLE `([^`]+)` \(\n(.*?)\n\) ENGINE=[^;]+;", source, re.S):
        table, body = match.groups()
        columns = []
        counts[table] = 0
        for line in body.splitlines():
            line = line.strip().rstrip(",")
            index = re.fullmatch(r"(UNIQUE )?KEY `([^`]+)` (\(.*\))", line)
            if index:
                unique, name, fields = index.groups()
                fields = fields.replace("`", '"')
                indexes.append(
                    f'CREATE {"UNIQUE " if unique else ""}INDEX "{name}" ON "{table}" {fields};'
                )
                continue
            line = re.sub(r" CHARACTER SET \w+ COLLATE \w+", "", line)
            line = line.replace(" unsigned", "").replace("longtext", "text")
            if "AUTO_INCREMENT" in line:
                column = re.match(r"`([^`]+)`", line)[1]
                line = line.replace("NOT NULL AUTO_INCREMENT", "GENERATED BY DEFAULT AS IDENTITY")
                # Preserve the dump's next ID, including gaps above MAX(id).
                next_id = re.search(r"AUTO_INCREMENT=(\d+)", match.group())
                floor = int(next_id[1]) if next_id else 1
                sequences.append(
                    f"SELECT setval(pg_get_serial_sequence('{table}', '{column}'), GREATEST(COALESCE((SELECT MAX(\"{column}\") FROM \"{table}\"), 0) + 1, {floor}), false);"
                )
            line = line.replace("`", '"')
            if not (line.startswith('"') or line.startswith("PRIMARY KEY")):
                raise ValueError(f"Unsupported definition: {line}")
            columns.append("  " + line)
        schema.append(f'CREATE TABLE "{table}" (\n' + ",\n".join(columns) + "\n);")
    for line in source.splitlines():
        if not line.startswith("INSERT INTO "):
            continue
        match = re.fullmatch(r"INSERT INTO `([^`]+)` VALUES (.*);", line)
        if not match:
            raise ValueError("Unsupported INSERT")
        table, data = match.groups()
        converted, rows = values(data)
        counts[table] += rows
        suffix = " ON CONFLICT (id) DO NOTHING" if table == "roles" else ""
        seed.append(f'INSERT INTO "{table}" VALUES {converted}{suffix};')
    if len(counts) != source.count("CREATE TABLE "):
        raise ValueError("Unparsed table definitions")
    header = "-- Generated by scripts/convert_mysql_dump.py; do not edit.\n"
    (MIGRATIONS / "000001_init_schema.up.sql").write_text(
        header + "\n\n".join(schema + indexes) + "\n"
    )
    (MIGRATIONS / "000001_init_schema.down.sql").write_text(
        header + "\n".join(f'DROP TABLE "{t}";' for t in reversed(counts)) + "\n"
    )
    # No DROP/TRUNCATE: importing into a populated database must fail atomically.
    (ROOT / "infra/database/clims_postgres_seed.sql").write_text(
        header
        + "BEGIN;\nSET LOCAL standard_conforming_strings = on;\n"
        + "\n".join(seed + sequences)
        + "\nCOMMIT;\n"
    )
    manifest = {
        "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        "rows": counts,
        "total_rows": sum(counts.values()),
    }
    (ROOT / "infra/database/seed_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Converted {len(counts)} tables and {sum(counts.values())} rows")


if __name__ == "__main__":
    convert()
